"""Dependency-free WCAG/CVD audit of the specification, not application code."""
import json, math, re
from pathlib import Path
from itertools import combinations
ROOT = Path(__file__).resolve().parent
TOKENS = json.loads((ROOT / 'tokens.json').read_text())
# Machado, Oliveira, Fernandes (2009), severity 1.0, linear sRGB.
MATRICES = {
 'protanopia': [[.152286,1.052583,-.204868],[.114503,.786281,.099216],[-.003882,-.048116,1.051998]],
 'deuteranopia': [[.367322,.860646,-.227968],[.280085,.672501,.047413],[-.011820,.042940,.968881]],
 'tritanopia': [[1.255528,-.076749,-.178779],[-.078411,.930809,.147602],[.004733,.691367,.303900]],
}
